"""Zip the prepared dataset for training on Google Colab.

Only the splits needed for training and evaluation are packed (train, val, test);
the `export` split is reserved for the demo and stays local. The data.yaml inside
the zip has no absolute paths, so it works wherever the zip is extracted.

Images are already compressed (PNG/JPEG), so files are stored without compression:
the zip is created quickly and is barely larger than the images themselves.

Usage (from the backend/ folder):
    uv run python scripts/package_dataset.py --src D:/datasets/hardhat-prepared \
        --out D:/datasets/hardhat-prepared.zip
Then upload the zip to Google Drive: MyDrive/annotator/hardhat-prepared.zip
"""

from __future__ import annotations

import argparse
import sys
import zipfile
from pathlib import Path

SPLITS = ("train", "val", "test")
# No `path:` key: Ultralytics then uses the folder of data.yaml as the dataset root.
# (`path: .` would mean the current working directory, not this folder.)
DATA_YAML = """\
# Generated by package_dataset.py
train: train/images
val: val/images
test: test/images
names:
  0: helmet
  1: head
"""


def package(src: Path, out: Path) -> int:
    """Write the zip and return the number of files packed."""
    files = [f for split in SPLITS for f in sorted((src / split).rglob("*")) if f.is_file()]
    out.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(out, "w", compression=zipfile.ZIP_STORED) as zf:
        zf.writestr("data.yaml", DATA_YAML)
        for i, file in enumerate(files, 1):
            zf.write(file, file.relative_to(src).as_posix())
            if i % 1000 == 0:
                print(f"  {i}/{len(files)} files")
    return len(files)


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--src", type=Path, required=True, help="output of prepare_dataset.py")
    parser.add_argument("--out", type=Path, required=True, help="zip file to create")
    args = parser.parse_args()

    missing = [s for s in SPLITS if not (args.src / s / "images").is_dir()]
    if missing:
        print(f"error: {args.src} has no {', '.join(missing)} split - run prepare_dataset.py")
        return 1

    count = package(args.src, args.out)
    size_mb = args.out.stat().st_size / 1024**2
    print(f"Wrote {args.out} ({count} files, {size_mb:.0f} MB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
